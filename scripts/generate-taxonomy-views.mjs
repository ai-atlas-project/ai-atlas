#!/usr/bin/env node
import {readFile, writeFile, mkdir, readdir, unlink} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const vault = 'obsidian/AI Atlas Vault';
const marker = '<!-- Generated by scripts/generate-taxonomy-views.mjs; do not edit. -->';
const quote = JSON.stringify;
const markdown = s => s.replace(/[\\`*_[\]<>#]/g, '\\$&');
const mermaid = s => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// Array order in the canonical JSON is the display order in every view.
export function renderViews(raw) {
  const data = JSON.parse(raw);
  const branches = data.level_1;
  const nodes = [data.level_0, ...branches.flatMap(b => [b, ...b.level_2])];
  const names = new Map(), ids = new Set(), filenames = new Set();
  for (const n of nodes) {
    if (!/^ai:[a-z0-9]+(?:-[a-z0-9]+)*$/.test(n.id) || ids.has(n.id)) throw Error(`Invalid or duplicate ID: ${n.id}`);
    if (typeof n.name !== 'string' || !n.name || /[\\/:*?"<>|\[\]\r\n]/.test(n.name) || /[. ]$/.test(n.name) || /^(con|prn|aux|nul|com[1-9]|lpt[1-9])(?:\.|$)/i.test(n.name)) throw Error(`Unsafe note name: ${n.name}`);
    if (names.has(n.name) || filenames.has(n.name.toLowerCase())) throw Error(`Duplicate note name: ${n.name}`);
    if (!Array.isArray(n.children) || ![0,1,2].includes(n.hierarchy_level)) throw Error(`Unsupported hierarchy: ${n.id}`);
    ids.add(n.id); names.set(n.name,n); filenames.add(n.name.toLowerCase());
  }
  const sameNames = (actual, expected) => actual.length === expected.length && new Set(actual).size === actual.length && actual.every(x => expected.includes(x));
  if (data.level_0.hierarchy_level !== 0 || !sameNames(data.level_0.children, branches.map(b => b.name))) throw Error('Root children do not match branches');
  for (const b of branches) {
    if (b.hierarchy_level !== 1 || b.parent !== data.level_0.name || !sameNames(b.children, b.level_2.map(n => n.name))) throw Error(`Invalid branch: ${b.id}`);
    for (const n of b.level_2) if (n.hierarchy_level !== 2 || n.parent !== b.name || n.children.length) throw Error(`Invalid leaf: ${n.id}`);
  }
  const notePath = n => n.hierarchy_level === 0 ? '00 Artificial Intelligence' : `Level ${n.hierarchy_level}/${n.name}`;
  const children = n => n.hierarchy_level === 0 ? branches : n.hierarchy_level === 1 ? n.level_2 : [];
  const wiki = n => `[[${notePath(n)}|${n.name}]]`;
  const out = new Map();
  let md = `# AI Atlas — Clean Hierarchy v${data.version}\n\n${marker}\n\nSource: [canonical JSON](ai-taxonomy-l1-l2.json). Level means hierarchy depth; concept type is separate.\n\n## Level 0\n\n- ${markdown(data.level_0.name)}\n\n## Level 1 and Level 2\n`;
  let markmap = `# ${markdown(data.level_0.name)}\n\n${marker}\n`;
  const graphId = n => n.id.replace(':','__').replaceAll('-','_');
  let graph = `# AI Atlas — L0–L2 hierarchy\n\n${marker}\n\nPrimary hierarchy only; arrows do not represent non-hierarchical relations.\n\n\`\`\`mermaid\nflowchart TD\n`;
  for (const n of nodes) graph += `  ${graphId(n)}["${mermaid(n.name)}"]\n`;
  for (const n of nodes) for (const c of children(n)) graph += `  ${graphId(n)} --> ${graphId(c)}\n`;
  graph += '```\n';
  for (const [i,b] of branches.entries()) {
    md += `\n### ${i+1}. ${markdown(b.name)}\n\n${b.level_2.map(n => '- '+markdown(n.name)).join('\n')}\n`;
    markmap += `\n## ${markdown(b.name)}\n${b.level_2.map(n => '\n### '+markdown(n.name)+'\n').join('')}`;
  }
  out.set('taxonomy/ai-taxonomy-l1-l2.md',md);
  out.set('markmap/ai-atlas-markmap.md',markmap);
  out.set('mermaid/ai-atlas-mermaid.md',graph);
  out.set('viewer/fieldguide/data/taxonomy.json',raw);
  for (const n of nodes) {
    const kids = children(n);
    let note = `---\nproject: "AI Atlas"\ngenerated_by: "scripts/generate-taxonomy-views.mjs"\nid: ${quote(n.id)}\nhierarchy_level: ${n.hierarchy_level}\nhierarchy_level_name: ${quote(n.hierarchy_level_name)}\nconcept_type: ${quote(n.concept_type)}\nstability: ${quote(n.stability)}\nparent: ${n.hierarchy_level === 0 ? 'null' : quote(n.parent)}\nchildren:${kids.length ? '\n'+kids.map(c => '  - '+quote(c.name)).join('\n') : ' []'}\n---\n\n# ${markdown(n.name)}\n\n${marker}\n\n## Description\n\n${n.description}\n`;
    if (n.hierarchy_level > 0) note += `\n## Parent\n\n- ${wiki(names.get(n.parent))}\n`;
    note += kids.length ? `\n## Level ${n.hierarchy_level+1} branches\n\n${kids.map(c => '- '+wiki(c)).join('\n')}\n` : '\n## Children\n\nNo children are included in the current Level 1–Level 2 taxonomy.\n';
    out.set(`${vault}/${notePath(n)}.md`,note);
  }
  return out;
}

async function noteFiles(base, relative) {
  let entries;
  try { entries = await readdir(path.join(base, relative), {withFileTypes:true}); }
  catch (e) { if (e.code === 'ENOENT') return []; throw e; }
  const result = [];
  for (const e of entries) {
    const p = `${relative}/${e.name}`;
    if (e.isDirectory()) result.push(...await noteFiles(base,p));
    else if (e.name.endsWith('.md')) result.push(p);
  }
  return result;
}

// Check mode is read-only and reports missing, stale, and obsolete outputs.
export async function syncViews(base, outputs, write = false) {
  const extras = (await Promise.all([1,2].map(n => noteFiles(base,`${vault}/Level ${n}`)))).flat().filter(p => !outputs.has(p));
  const changes = [];
  // Preflight prevents partially overwriting the vault if a personal note is found.
  for (const p of extras) {
    const content = await readFile(path.join(base,p),'utf8');
    if (write && !content.includes(marker)) throw Error(`Refusing to remove unrecognized note: ${p}. Move personal notes outside Level 1/Level 2 or review this obsolete file manually.`);
    changes.push(`Obsolete: ${p}`);
  }
  for (const [p,expected] of outputs) {
    let actual;
    try { actual = await readFile(path.join(base,p),'utf8'); }
    catch (e) { if (e.code !== 'ENOENT') throw e; }
    if (actual !== expected) {
      changes.push(`${actual === undefined ? 'Missing' : 'Stale'}: ${p}`);
      if (write) { await mkdir(path.dirname(path.join(base,p)),{recursive:true}); await writeFile(path.join(base,p),expected); }
    }
  }
  if (write) for (const p of extras) await unlink(path.join(base,p));
  return changes;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try {
    const args = process.argv.slice(2);
    if (args.length !== 1 || !['--write','--check'].includes(args[0])) throw Error('Usage: node scripts/generate-taxonomy-views.mjs --write|--check');
    const outputs = renderViews(await readFile(path.join(root,'taxonomy/ai-taxonomy-l1-l2.json'),'utf8'));
    const changes = await syncViews(root,outputs,args[0] === '--write');
    if (changes.length && args[0] === '--check') {
      console.error(changes.join('\n')+'\nRun node scripts/generate-taxonomy-views.mjs --write and review the diff.');
      process.exitCode = 1;
    } else console.log(`${args[0] === '--write' ? 'Generated' : 'Verified'} ${outputs.size} taxonomy views; ${changes.length} changes.`);
  } catch (e) { console.error(e.message); process.exitCode = 1; }
}
